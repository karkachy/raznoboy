CREATE TABLE IF NOT EXISTS Accounts (
  Id INTEGER PRIMARY KEY, Name TEXT NOT NULL, Email TEXT NOT NULL UNIQUE, PasswordHash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS Concerts (Id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS EventDetails (
  Id TEXT PRIMARY KEY REFERENCES Concerts(Id), title TEXT NOT NULL, genre TEXT NOT NULL, kind TEXT NOT NULL,
  city TEXT NOT NULL, date TEXT NOT NULL, time TEXT, place TEXT NOT NULL, cover TEXT NOT NULL,
  artist TEXT NOT NULL, description TEXT NOT NULL, source TEXT NOT NULL, credit TEXT NOT NULL,
  featured INTEGER NOT NULL, ticketUrl TEXT, coverPosition TEXT, dateLabel TEXT
);
CREATE TABLE IF NOT EXISTS SeedVotes (
  ConcertId TEXT NOT NULL REFERENCES Concerts(Id), Slot INTEGER NOT NULL,
  Score INTEGER NOT NULL CHECK(Score BETWEEN 1 AND 5), PRIMARY KEY(ConcertId, Slot)
);
CREATE TABLE IF NOT EXISTS Votes (
  ConcertId TEXT NOT NULL REFERENCES Concerts(Id), AccountId INTEGER NOT NULL REFERENCES Accounts(Id),
  Score INTEGER NOT NULL CHECK(Score BETWEEN 1 AND 5), PRIMARY KEY(ConcertId, AccountId)
);
CREATE TABLE IF NOT EXISTS Tickets (
  Number INTEGER PRIMARY KEY AUTOINCREMENT, AccountId INTEGER NOT NULL REFERENCES Accounts(Id),
  ConcertId TEXT NOT NULL REFERENCES Concerts(Id), RequestId TEXT NOT NULL,
  Title TEXT NOT NULL, EventDate TEXT NOT NULL, EventTime TEXT, City TEXT NOT NULL, Place TEXT NOT NULL,
  UNIQUE(AccountId, ConcertId, RequestId)
);
CREATE TABLE IF NOT EXISTS Sessions (
  TokenHash TEXT PRIMARY KEY, AccountId INTEGER NOT NULL REFERENCES Accounts(Id), ExpiresAt INTEGER NOT NULL
);
